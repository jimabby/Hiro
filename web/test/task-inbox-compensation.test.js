const fs = require('fs'), os = require('os'), path = require('path')
const { stub, service, createChecker } = require('./helpers')
const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'hiro-inbox-'))
process.on('exit', () => fs.rmSync(tmp, { recursive: true, force: true }))
stub({ './config': { CONFIG_DIR: tmp, load: () => ({}), update: () => ({}) } })
const db = service('database'), hub = service('featureHub')
const { check, done } = createChecker()
;(async () => {
  await db.init()
  const add = (url, salary = '') => db.insertApplication({ job_title: 'Engineer', company: 'Example', platform: 'Seek', job_url: url, job_description: '', status: 'held', salary }).id
  const a = add('https://example.com/a', 'AUD $100,000 + $20,000 bonus'), b = add('https://example.com/b', 'GBP 60,000')
  db.updateChecklist(a, { title: 'Portfolio', due: '2026-10-20' })
  db.setNextAction(a, { date: '2026-10-19', note: 'Call recruiter' })
  db.saveOffer(b, { currency: 'GBP', baseSalary: 60000, bonus: 10000, benefits: 'Health insurance', respondBy: '2026-10-21' })
  let inbox = hub.taskInbox()
  check('inbox combines checklist follow-up and offer', inbox.map(t => t.kind), ['follow-up', 'checklist', 'offer'])
  hub.completeInboxTask(inbox[0]); hub.completeInboxTask(inbox[1])
  check('completed tasks leave inbox', hub.taskInbox().map(t => t.kind), ['offer'])
  db.saveOffer(a, { currency: 'AUD', baseSalary: 100000, bonus: 20000 })
  const board = db.getOffers()
  check('mixed currencies have no misleading best', board.best, null)
  check('each currency keeps its own total', board.byCurrency.map(g => g.best).sort((x, y) => x - y), [70000, 120000])
  check('benefits survive independently of cash', board.offers.find(o => o.applicationId === b).benefits, 'Health insurance')
  check('benchmark only includes matching currency', db.getSalaryBenchmark('Engineer', { currency: 'GBP' }).median, 60000)
  check('unknown currency has no benchmark', db.getSalaryBenchmark('Engineer', { currency: '' }).sample, 0)
  db.updateApplicationComment(a, 'Desktop note')
  db.recordSyncConflict({ applicationId: a, field: 'comment', localValue: 'Desktop note', remoteValue: 'Phone note', resolvedAs: 'local-kept' })
  check('notes can be merged', db.applyConflictResolution(db.getSyncConflicts()[0].id, 'merge').success, true)
  check('merge preserves both notes', db.getApplication(a).comment, 'Desktop note\n\nPhone note')
  const before = db.getApplication(a).checklist
  db.recordSyncConflict({ applicationId: a, field: 'checklist', localValue: before, remoteValue: JSON.stringify([{ id: 'phone-task', title: 'References', done: false }]), resolvedAs: 'local-kept' })
  check('checklists can be merged', db.applyConflictResolution(db.getSyncConflicts()[0].id, 'merge').success, true)
  check('checklist merge retains both tasks', db.getChecklist(a).length, 2)
  db.recordSyncConflict({ applicationId: a, field: 'comment', localValue: 'Old value', remoteValue: 'Phone value', resolvedAs: 'local-kept' })
  check('stale conflict cannot overwrite a newer edit', db.applyConflictResolution(db.getSyncConflicts()[0].id).success, false)
  const rate = add('https://example.com/rate', '$60.50 per hour')
  db.backfillSalaryColumns()
  check('historical salary backfill keeps fractional rates', db.getApplication(rate).salary_min, 119548)
  check('salary backfill is idempotent', db.backfillSalaryColumns().updated, 0)
  done()
})().catch(e => { console.error(e); process.exitCode = 1 })
